// Clean and parse OpenRouter JSON outputs
function parseDynamicNodeJSON(rawText) {
    try {
        // Clean markdown blocks
        let cleaned = rawText.trim();
        if (cleaned.startsWith("```")) {
            cleaned = cleaned.replace(/^```json/, "").replace(/^```/, "").replace(/```$/, "").trim();
        }
        
        // Find the first { and last } to extract JSON strictly
        const startIdx = cleaned.indexOf("{");
        const endIdx = cleaned.lastIndexOf("}");
        
        if (startIdx === -1 || endIdx === -1) {
            throw new Error("No JSON boundaries found in response");
        }
        
        cleaned = cleaned.substring(startIdx, endIdx + 1);
        return JSON.parse(cleaned);
    } catch (e) {
        console.warn("JSON Parse cleaning failed, attempting raw response parse:", e);
        // Fallback placeholder node in case parsing breaks
        return {
            text: "คือ... เมื่อกี้หนูเผลอคิดเรื่องโคฮารุจังเพลินไปหน่อยค่ะ! มาลุยโปรเจกต์ต่อกันนะคะ!",
            expression: "happy",
            affectionChange: 0,
            choices: [
                { id: "fallback_1", hint: "ลุยตั้งค่าโปรเจกต์โคฮารุจังกันต่อ", next: "ch1_setup_env", affectionChange: 1 },
                { id: "fallback_2", hint: "ไปออกแบบ System Prompt ของโคฮารุจังกัน", next: "ch2_start", affectionChange: 1 }
            ]
        };
    }
}

// OpenRouter REST Call (the API key remains on the backend)
async function callOpenRouterAPI(promptText) {
    const response = await fetch(API_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ prompt: promptText })
    });

    if (!response.ok) {
        const err = await response.json().catch(() => ({ error: response.statusText }));
        throw new Error(`API Error: ${response.status} - ${err.error || response.statusText}`);
    }

    const data = await response.json();
    if (data.text) {
        return data.text;
    } else {
        throw new Error("Invalid response from server");
    }
}

